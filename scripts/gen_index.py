"""Generate a compact symbol-and-line-number index for fast codebase navigation."""

from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "docs" / "SYMBOL_INDEX.md"

TS_EXPORT_RE = re.compile(
    r"^export\s+(?:default\s+)?(?:async\s+)?"
    r"(function|class|interface|type|const|enum)\s+([A-Za-z0-9_]+)"
)


def _extract_python_symbols(path: Path) -> list[str]:
    source = path.read_text(encoding="utf-8")
    tree = ast.parse(source, filename=str(path))
    symbols: list[str] = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            symbols.append(f"`{node.name}()` L{node.lineno}")
        elif isinstance(node, ast.ClassDef):
            methods = [
                f"`{m.name}` L{m.lineno}"
                for m in node.body
                if isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))
                and not m.name.startswith("__")
            ]
            suffix = f" ({', '.join(methods[:8])}{'...' if len(methods) > 8 else ''})" if methods else ""
            symbols.append(f"`class {node.name}` L{node.lineno}{suffix}")
    return symbols


def _extract_ts_symbols(path: Path) -> list[str]:
    symbols: list[str] = []
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        match = TS_EXPORT_RE.match(line)
        if match:
            kind, name = match.groups()
            symbols.append(f"`{kind} {name}` L{lineno}")
    return symbols


def _collect_section(base: Path, pattern: str, extractor: str) -> list[str]:
    lines: list[str] = []
    for path in sorted(base.rglob(pattern)):
        if "__pycache__" in path.parts:
            continue
        if extractor == "ts" and (
            ".test." in path.name or ".generated." in path.name or path.name == "vite-env.d.ts"
        ):
            continue
        rel = path.relative_to(ROOT).as_posix()
        symbols = _extract_python_symbols(path) if extractor == "py" else _extract_ts_symbols(path)
        if symbols:
            lines.append(f"- **{rel}**: " + "; ".join(symbols))
    return lines


def build_index() -> str:
    py_lines = _collect_section(ROOT / "src" / "quartz", "*.py", "py")
    ts_lines = [
        *_collect_section(ROOT / "webapp" / "src", "*.ts", "ts"),
        *_collect_section(ROOT / "webapp" / "src", "*.tsx", "ts"),
    ]
    ts_lines.sort()

    parts = [
        "# Symbol Index",
        "",
        "Auto-generated by `scripts/gen_index.py`. Jump directly to a symbol's line number with `read(path, start, end)`.",
        "",
        "## Python (`src/quartz/`)",
        "",
        *py_lines,
        "",
        "## TypeScript (`webapp/src/`)",
        "",
        *ts_lines,
        "",
    ]
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Output markdown path")
    parser.add_argument("--check", action="store_true", help="Exit non-zero if index is out of date")
    args = parser.parse_args()

    content = build_index()
    if args.check:
        existing = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if existing != content:
            print(f"{args.output} is out of date. Run: uv run python scripts/gen_index.py")
            return 1
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"Wrote {args.output.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
