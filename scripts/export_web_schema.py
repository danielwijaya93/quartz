"""Export Pydantic v2 wire schemas from `quartz.web.schemas` to TypeScript."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

from pydantic import TypeAdapter

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from quartz.web.schemas import REST_REQUEST_MODELS, ClientFrame  # noqa: E402

HEADER = "// AUTO-GENERATED by scripts/export_web_schema.py — do not edit manually\n"
OUTPUT_PATH = ROOT / "webapp" / "src" / "protocol.generated.ts"


def _ts_type(schema: dict[str, Any], defs: dict[str, Any]) -> str:
    if "$ref" in schema:
        ref = schema["$ref"]
        name = ref.rsplit("/", 1)[-1]
        return name
    if "const" in schema:
        return repr(schema["const"]).replace("'", '"')
    if "enum" in schema:
        return " | ".join(
            repr(v).replace("'", '"') if isinstance(v, str) else str(v).lower()
            for v in schema["enum"]
        )
    if "anyOf" in schema:
        parts = [_ts_type(sub, defs) for sub in schema["anyOf"]]
        # Deduplicate while preserving order
        seen: list[str] = []
        for p in parts:
            if p not in seen:
                seen.append(p)
        return " | ".join(seen)

    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        items = schema.get("items", {})
        item_ts = _ts_type(items, defs) if isinstance(items, dict) else "unknown"
        return f"({item_ts})[]" if " | " in item_ts else f"{item_ts}[]"
    if kind == "object":
        addl = schema.get("additionalProperties")
        if isinstance(addl, dict):
            return f"Record<string, {_ts_type(addl, defs)}>"
        return "Record<string, unknown>"
    return "unknown"


def _render_interface(name: str, schema: dict[str, Any], defs: dict[str, Any]) -> str:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for prop_name, prop_schema in props.items():
        ts = _ts_type(prop_schema, defs)
        opt = "" if prop_name in required else "?"
        lines.append(f"  {prop_name}{opt}: {ts};")
    lines.append("}")
    return "\n".join(lines)


def render_typescript() -> str:
    """Render TypeScript interfaces and unions for all `quartz.web.schemas` models."""
    ws_schema = TypeAdapter(ClientFrame).json_schema(by_alias=True)
    all_defs: dict[str, Any] = dict(ws_schema.get("$defs", {}))

    rest_schemas: dict[str, dict[str, Any]] = {}
    for model in REST_REQUEST_MODELS:
        m_schema = model.model_json_schema(by_alias=True)
        all_defs.update(m_schema.get("$defs", {}))
        rest_schemas[model.__name__] = m_schema

    blocks: list[str] = [HEADER.rstrip()]

    # Shared / nested definitions first (excluding frame models)
    frame_names: list[str] = []
    for variant in ws_schema.get("oneOf", ws_schema.get("anyOf", [])):
        if "$ref" in variant:
            frame_names.append(variant["$ref"].rsplit("/", 1)[-1])

    shared_names = [k for k in sorted(all_defs) if k not in frame_names]
    for name in shared_names:
        blocks.append(_render_interface(name, all_defs[name], all_defs))

    for name in frame_names:
        if name in all_defs:
            blocks.append(_render_interface(name, all_defs[name], all_defs))

    if frame_names:
        union_body = "\n  | ".join(frame_names)
        blocks.append(f"export type GeneratedClientFrame =\n  | {union_body};")

    for name, m_schema in rest_schemas.items():
        blocks.append(_render_interface(name, m_schema, all_defs))

    return "\n\n".join(blocks) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export quartz web Pydantic schemas to TypeScript.")
    parser.add_argument("--check", action="store_true", help="Exit non-zero if generated file is stale.")
    args = parser.parse_args(argv)

    rendered = render_typescript()
    if args.check:
        if not OUTPUT_PATH.is_file() or OUTPUT_PATH.read_text(encoding="utf-8") != rendered:
            print(f"Drift detected in {OUTPUT_PATH}. Run scripts/export_web_schema.py.", file=sys.stderr)
            return 1
        return 0

    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
